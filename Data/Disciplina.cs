using System.ComponentModel.DataAnnotations;
using System.Reflection;
using Microsoft.AspNetCore.Mvc.ModelBinding.Validation;
using Microsoft.EntityFrameworkCore;

namespace SistemaEscolar.Data;

// Disciplina e as séries em que ela é oferecida. Não é excluída: fica inativa.
public class Disciplina
{
    public int Id { get; set; }

    [Required(ErrorMessage = "Informe o nome da disciplina")]
    [StringLength(80)]
    [Nome]
    [Display(Name = "Nome")]
    public string Nome { get; set; } = "";

    public bool Ativa { get; set; } = true;

    [ValidateNever]
    public List<DisciplinaSerie> Series { get; set; } = new();
}

public class DisciplinaSerie
{
    public int DisciplinaId { get; set; }
    public Serie Serie { get; set; }
}

public static class SerieExt
{
    public static string Nome(this Serie s) =>
        typeof(Serie).GetField(s.ToString())?.GetCustomAttribute<DisplayAttribute>()?.Name ?? s.ToString();

    public static string Nivel(this Serie s) => (int)s < 10 ? "Educação Infantil" : (int)s < 20 ? "Ensino Fundamental" : "Ensino Médio";

    /// <summary>Texto curto: "Fundamental completo" ou a lista de séries do nível.</summary>
    public static string Resumo(IEnumerable<Serie> series)
    {
        var sel = series.ToHashSet();
        var partes = new List<string>();
        foreach (var g in Enum.GetValues<Serie>().GroupBy(s => s.Nivel()))
        {
            var doNivel = g.Where(sel.Contains).ToList();
            if (doNivel.Count == 0) continue;
            partes.Add(doNivel.Count == g.Count()
                ? g.Key.Replace("Educação ", "").Replace("Ensino ", "") + " completo"
                : string.Join(", ", doNivel.Select(s => s.Nome())));
        }
        return partes.Count == 0 ? "—" : string.Join(" · ", partes);
    }
}

public static class TabelasDisciplinas
{
    public static void Preparar(EscolaContext db)
    {
        db.Database.ExecuteSqlRaw("""
            CREATE TABLE IF NOT EXISTS "Disciplinas" (
                "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "Nome" text NOT NULL,
                "Ativa" boolean NOT NULL
            );
            CREATE UNIQUE INDEX IF NOT EXISTS "IX_Disciplinas_Nome" ON "Disciplinas" ("Nome");
            CREATE TABLE IF NOT EXISTS "DisciplinaSeries" (
                "DisciplinaId" integer NOT NULL REFERENCES "Disciplinas" ("Id") ON DELETE CASCADE,
                "Serie" integer NOT NULL,
                PRIMARY KEY ("DisciplinaId", "Serie")
            );
            """);
    }

    // Catálogo inicial (botão "Carregar disciplinas padrão"). Pode ser editado depois.
    public static (string Nome, Serie[] Series)[] Padrao()
    {
        var infantil = new[] { Serie.Maternal, Serie.PreI, Serie.PreII };
        var fund = Enum.GetValues<Serie>().Where(s => (int)s is >= 10 and < 20).ToArray();
        var medio = Enum.GetValues<Serie>().Where(s => (int)s >= 20).ToArray();
        var fundMedio = fund.Concat(medio).ToArray();
        return new[]
        {
            ("Linguagem", infantil),
            ("Noções de Matemática", infantil),
            ("Movimento", infantil),
            ("Português", fundMedio),
            ("Matemática", fundMedio),
            ("Ciências", fund),
            ("História", fundMedio),
            ("Geografia", fundMedio),
            ("Inglês", fundMedio),
            ("Artes", infantil.Concat(fundMedio).ToArray()),
            ("Educação Física", fundMedio),
            ("Física", medio),
            ("Química", medio),
            ("Biologia", medio),
            ("Filosofia", medio),
            ("Sociologia", medio),
        };
    }
}
