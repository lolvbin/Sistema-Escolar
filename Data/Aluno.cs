using System.ComponentModel.DataAnnotations;
using Microsoft.AspNetCore.Mvc.ModelBinding;
using Microsoft.EntityFrameworkCore;

namespace SistemaEscolar.Data;

// Cadastro do aluno e da família. Série, turno e ano letivo continuam na Matrícula.
public class Aluno
{
    public int Id { get; set; }

    [Required(ErrorMessage = "Informe o nome do aluno")]
    [StringLength(120)]
    [Nome]
    [Display(Name = "Nome do aluno")]
    public string Nome { get; set; } = "";

    [Required(ErrorMessage = "Informe a data de nascimento (dd/mm/aaaa)")]
    [DataType(DataType.Date)]
    [Display(Name = "Data de nascimento")]
    public DateTime? DataNascimento { get; set; }

    [Required(ErrorMessage = "Informe o CPF do aluno")]
    [StringLength(14)]
    [Cpf]
    [Display(Name = "CPF do aluno")]
    public string Cpf { get; set; } = "";

    [StringLength(500)]
    [Display(Name = "Observações")]
    public string? Observacoes { get; set; }

    [Display(Name = "O responsável financeiro é o mesmo responsável acadêmico")]
    public bool MesmoResponsavel { get; set; } = true;

    public Responsavel Academico { get; set; } = new();
    public Responsavel Financeiro { get; set; } = new();

    public void Validar(ModelStateDictionary ms)
    {
        if (MesmoResponsavel)
        {
            foreach (var k in ms.Keys.Where(k => k.Contains("Financeiro")).ToList())
                ms.Remove(k);
        }

        if (DataNascimento is { } d && (d.Date > DateTime.Today || d.Year < DateTime.Today.Year - 30))
            ms.AddModelError("DataNascimento", "Data de nascimento inválida");
    }

    public void Normalizar()
    {
        Nome = Nome.Trim();
        Cpf = Texto.FormatarCpf(Cpf);
        Academico.Normalizar();
        if (MesmoResponsavel) Financeiro = Academico.Copia();
        else Financeiro.Normalizar();
    }
}

public static class Tabelas
{
    // EnsureCreated não adiciona tabelas em banco existente, então criamos as novas na mão.
    // Os nomes das colunas dos responsáveis seguem o padrão do EF para owned types (Academico_Nome...).
    public static void Preparar(EscolaContext db)
    {
        db.Database.ExecuteSqlRaw("""
            CREATE TABLE IF NOT EXISTS "Alunos" (
                "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "Nome" text NOT NULL,
                "DataNascimento" date NOT NULL,
                "Cpf" text NOT NULL,
                "Observacoes" text NULL,
                "MesmoResponsavel" boolean NOT NULL,
                "Academico_Nome" text NOT NULL,
                "Academico_Cpf" text NOT NULL,
                "Academico_Telefone" text NOT NULL,
                "Academico_Email" text NOT NULL,
                "Financeiro_Nome" text NOT NULL,
                "Financeiro_Cpf" text NOT NULL,
                "Financeiro_Telefone" text NOT NULL,
                "Financeiro_Email" text NOT NULL
            );
            CREATE UNIQUE INDEX IF NOT EXISTS "IX_Alunos_Cpf" ON "Alunos" ("Cpf");
            """);

        MigrarMatriculas(db);
    }

    // Matrícula antiga (com aluno e responsáveis dentro) -> Aluno + Matrícula com AlunoId.
    // A tabela antiga NÃO é apagada: fica como "Matriculas_antiga" até você conferir.
    static void MigrarMatriculas(EscolaContext db)
    {
        var antiga = db.Database.SqlQueryRaw<int>("""
            SELECT count(*)::int AS "Value" FROM information_schema.columns
            WHERE table_schema = current_schema() AND table_name = 'Matriculas' AND column_name = 'AlunoNome'
            """).AsEnumerable().First() > 0;

        using var tx = db.Database.BeginTransaction();

        if (antiga)
        {
            db.Database.ExecuteSqlRaw("""
                INSERT INTO "Alunos" ("Nome","DataNascimento","Cpf","Observacoes","MesmoResponsavel",
                    "Academico_Nome","Academico_Cpf","Academico_Telefone","Academico_Email",
                    "Financeiro_Nome","Financeiro_Cpf","Financeiro_Telefone","Financeiro_Email")
                SELECT DISTINCT ON ("Cpf") "AlunoNome","DataNascimento","Cpf",NULL,"MesmoResponsavel",
                    "Academico_Nome","Academico_Cpf","Academico_Telefone","Academico_Email",
                    "Financeiro_Nome","Financeiro_Cpf","Financeiro_Telefone","Financeiro_Email"
                FROM "Matriculas" ORDER BY "Cpf","Id" DESC
                ON CONFLICT ("Cpf") DO NOTHING;
                ALTER TABLE "Matriculas" RENAME TO "Matriculas_antiga";
                """);
        }

        db.Database.ExecuteSqlRaw("""
            CREATE TABLE IF NOT EXISTS "Matriculas" (
                "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "AlunoId" integer NOT NULL REFERENCES "Alunos" ("Id") ON DELETE RESTRICT,
                "Serie" integer NOT NULL,
                "Turno" integer NOT NULL,
                "AnoLetivo" integer NOT NULL,
                "Status" integer NOT NULL,
                "DataMatricula" date NOT NULL,
                "Observacoes" text NULL
            );
            CREATE UNIQUE INDEX IF NOT EXISTS "IX_Matriculas_AlunoId_AnoLetivo" ON "Matriculas" ("AlunoId","AnoLetivo");
            """);

        if (antiga)
        {
            db.Database.ExecuteSqlRaw("""
                INSERT INTO "Matriculas" ("AlunoId","Serie","Turno","AnoLetivo","Status","DataMatricula","Observacoes")
                SELECT a."Id", m."Serie", m."Turno", m."AnoLetivo", m."Status", m."DataMatricula", m."Observacoes"
                FROM "Matriculas_antiga" m JOIN "Alunos" a ON a."Cpf" = m."Cpf"
                ORDER BY m."Id"
                ON CONFLICT ("AlunoId","AnoLetivo") DO NOTHING;
                """);
        }

        tx.Commit();
    }
}
